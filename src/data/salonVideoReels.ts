/**
 * Helper to get reels for a specific salon ID.
 * Returns tailored reels or falls back to category-matched reel.
 */
export function getReelsForSalon(salonId: string): SalonVideoReel[] {
  const matched = ALL_SALON_VIDEO_REELS.filter((r) => r.salonId === salonId);
  if (matched.length > 0) return matched;

  // Fallback: match by partial name or category
  const genericMatch = ALL_SALON_VIDEO_REELS.find((r) => 
    salonId.includes(r.salonId) || r.salonId.includes(salonId)
  );

  return genericMatch ? [genericMatch] : [ALL_SALON_VIDEO_REELS[0]];
}
